using System.Globalization;
using System.Text;
using Microsoft.EntityFrameworkCore;
using PromptLedger.Core.Data;
using PromptLedger.Core.Domain;

namespace PromptLedger.Core.Export;

/// <summary>
/// Renders PROMPT_LOG.md, the assessment deliverable. Each entry has the prompt, why it was sent,
/// and what was kept, changed or rejected, followed by the manual-changes section (deliverable 4).
/// Output is deterministic, so regenerating it without data changes produces no git diff.
/// </summary>
public sealed class PromptLogExporter(LedgerDbContext db)
{
    public async Task<string> RenderAsync(CancellationToken ct = default)
    {
        var sessions = await db.Sessions.AsNoTracking()
            .Include(s => s.Prompts.Where(p => p.IncludeInLog)).ThenInclude(p => p.Tags)
            .OrderBy(s => s.StartedAt)
            .ToListAsync(ct);
        var changes = await db.ManualChanges.AsNoTracking().OrderBy(c => c.CreatedAt).ToListAsync(ct);

        var prompts = sessions.SelectMany(s => s.Prompts).ToList();
        var md = new StringBuilder();
        md.AppendLine("# Prompt Log");
        md.AppendLine();
        md.AppendLine("> Generated by the Prompt Ledger (`tools/prompt-ledger`). Do not edit by hand: annotate prompts in the ledger and re-export.");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture,
            $"**{prompts.Count}** prompts across **{sessions.Count(s => s.Prompts.Count > 0)}** sessions · " +
            $"**{prompts.Count(p => p.HumanReviewed)}** human-reviewed · " +
            $"**{changes.Count}** manual changes");
        md.AppendLine();

        var outcomes = prompts.Where(p => p.Outcome != PromptOutcome.Unset)
            .GroupBy(p => p.Outcome).OrderBy(g => g.Key)
            .Select(g => $"{g.Key}: {g.Count()}").ToList();
        if (outcomes.Count > 0)
        {
            md.AppendLine("Outcomes: " + string.Join(" · ", outcomes));
            md.AppendLine();
        }

        var number = 0;
        foreach (var session in sessions.Where(s => s.Prompts.Count > 0))
        {
            md.AppendLine(CultureInfo.InvariantCulture,
                $"## Session: {Escape(session.Title ?? session.Id)} ({session.StartedAt.UtcDateTime:yyyy-MM-dd})");
            md.AppendLine();

            foreach (var p in session.Prompts.OrderBy(p => p.Sequence))
            {
                number++;
                RenderPrompt(md, number, p);
            }
        }

        md.AppendLine("## Manual changes made outside of AI");
        md.AppendLine();
        if (changes.Count == 0)
        {
            md.AppendLine("_None recorded yet._");
            md.AppendLine();
        }

        foreach (var c in changes)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"### {Escape(c.Title)}");
            md.AppendLine();
            var meta = new List<string> { c.CreatedAt.UtcDateTime.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture) };
            if (c.CommitSha is { Length: > 0 }) meta.Add($"commit `{c.CommitSha[..Math.Min(10, c.CommitSha.Length)]}`");
            md.AppendLine("_" + string.Join(" · ", meta) + "_");
            md.AppendLine();
            Section(md, "What changed", c.Description);
            Section(md, "Why", c.Reasoning);
            if (c.Files is { Length: > 0 })
            {
                md.AppendLine("**Files**");
                md.AppendLine();
                foreach (var f in c.Files.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                {
                    md.AppendLine(CultureInfo.InvariantCulture, $"- `{f}`");
                }

                md.AppendLine();
            }
        }

        return md.ToString().ReplaceLineEndings("\n");
    }

    public async Task WriteAsync(string path, CancellationToken ct = default)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await File.WriteAllTextAsync(path, await RenderAsync(ct), new UTF8Encoding(false), ct);
    }

    private static void RenderPrompt(StringBuilder md, int number, Prompt p)
    {
        md.AppendLine(CultureInfo.InvariantCulture, $"### {number}. {Escape(Headline(p.Text))}");
        md.AppendLine();

        var meta = new List<string> { p.SubmittedAt.UtcDateTime.ToString("yyyy-MM-dd HH:mm 'UTC'", CultureInfo.InvariantCulture) };
        meta.Add(p.HumanReviewed ? "✅ human-reviewed" : "⏳ not yet reviewed");
        if (p.Outcome != PromptOutcome.Unset) meta.Add($"outcome: **{p.Outcome.ToString().ToLowerInvariant()}**");
        if (p.Tags.Count > 0) meta.Add(string.Join(" ", p.Tags.OrderBy(t => t.Name, StringComparer.Ordinal).Select(t => $"`#{t.Name}`")));
        md.AppendLine(string.Join(" · ", meta));
        md.AppendLine();

        md.AppendLine("**Prompt**");
        md.AppendLine();
        foreach (var line in p.Text.ReplaceLineEndings("\n").Split('\n'))
        {
            md.AppendLine(line.Length == 0 ? ">" : "> " + line);
        }

        md.AppendLine();
        Section(md, "Why I sent it", p.Rationale);
        Section(md, "What I kept, changed or rejected", p.OutcomeNotes);
        Section(md, "Notes", p.Comment);
    }

    private static void Section(StringBuilder md, string heading, string? body)
    {
        if (string.IsNullOrWhiteSpace(body)) return;
        md.AppendLine(CultureInfo.InvariantCulture, $"**{heading}**");
        md.AppendLine();
        md.AppendLine(body.Trim().ReplaceLineEndings("\n"));
        md.AppendLine();
    }

    private static string Headline(string text)
    {
        var first = text.ReplaceLineEndings("\n").Split('\n').FirstOrDefault(l => l.Trim().Length > 0)?.Trim() ?? "";
        return first.Length <= 80 ? first : first[..77].TrimEnd() + "…";
    }

    private static string Escape(string s) => s.Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}
